-- ---------- Membros: só quem está aqui acessa os dados ----------
create table public.membros (
  user_id uuid primary key references auth.users(id) on delete cascade,
  nome text not null,
  criado_em timestamptz not null default now()
);

create or replace function public.eh_membro()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.membros m where m.user_id = (select auth.uid()));
$$;

create or replace function public.nome_usuario()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (select m.nome from public.membros m where m.user_id = (select auth.uid())),
    (select auth.jwt() ->> 'email'),
    'sistema'
  );
$$;

