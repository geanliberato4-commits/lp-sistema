-- Total de um pedido (itens + frete - desconto)
create or replace function public.total_pedido(p_pedido uuid)
returns numeric
language sql
stable
set search_path = ''
as $$
  select coalesce((select sum(i.quantidade * i.valor_unitario) from public.pedido_itens i where i.pedido_id = p_pedido), 0)
       + p.frete - p.desconto
  from public.pedidos p where p.id = p_pedido;
$$;

-- Não deixa receber mais do que o total do pedido (evita lançamento duplicado)
create or replace function public.checar_recebimento()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_total numeric;
  v_recebido numeric;
begin
  if new.pedido_id is null or new.tipo <> 'entrada' then
    return new;
  end if;
  v_total := coalesce(public.total_pedido(new.pedido_id), 0);
  select coalesce(sum(c.valor), 0) into v_recebido
    from public.caixa c
   where c.pedido_id = new.pedido_id and c.tipo = 'entrada'
     and (tg_op = 'INSERT' or c.id <> new.id);
  if v_recebido + new.valor > v_total + 0.009 then
    raise exception 'O valor passa do saldo a receber do pedido (saldo: R$ %).',
      replace(to_char(greatest(v_total - v_recebido, 0), 'FM999999990.00'), '.', ',')
      using errcode = 'P0001';
  end if;
  return new;
end;
$$;
create trigger caixa_checar_recebimento
  before insert or update on public.caixa
  for each row execute function public.checar_recebimento();

-- Registra no histórico do pedido quando um recebimento é lançado ou excluído
create or replace function public.historico_caixa()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' and new.pedido_id is not null then
    insert into public.pedido_historico (pedido_id, texto)
    values (new.pedido_id, 'Recebimento de R$ ' || replace(to_char(new.valor, 'FM999999990.00'), '.', ',') || ' (' || new.forma || ') lançado no caixa');
  elsif tg_op = 'DELETE' and old.pedido_id is not null then
    insert into public.pedido_historico (pedido_id, texto)
    values (old.pedido_id, 'Recebimento de R$ ' || replace(to_char(old.valor, 'FM999999990.00'), '.', ',') || ' excluído do caixa');
  end if;
  return null;
end;
$$;
create trigger caixa_historico
  after insert or delete on public.caixa
  for each row execute function public.historico_caixa();

-- Histórico automático de mudança de situação e data de atualização
create or replace function public.pedido_alterado()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  rotulos jsonb := '{"orcamento":"Orçamento","novo":"Novo","aguardando_pagamento":"Aguardando pagamento","aguardando_arte":"Aguardando arte","em_producao":"Em produção","pronto_envio":"Pronto para envio","enviado":"Enviado","finalizado":"Finalizado","cancelado":"Cancelado"}';
begin
  new.atualizado_em := now();
  if new.status is distinct from old.status then
    insert into public.pedido_historico (pedido_id, texto)
    values (new.id, (rotulos ->> old.status) || ' → ' || (rotulos ->> new.status));
  end if;
  if new.custo is distinct from old.custo or new.taxa_shopee is distinct from old.taxa_shopee then
    insert into public.pedido_historico (pedido_id, texto) values (new.id, 'Custos ajustados');
  end if;
  return new;
end;
$$;
create trigger pedidos_alterado
  before update on public.pedidos
  for each row execute function public.pedido_alterado();

