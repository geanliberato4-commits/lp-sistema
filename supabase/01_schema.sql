-- ---------- Pedidos ----------
create table public.pedidos (
  id uuid primary key default gen_random_uuid(),
  numero integer generated by default as identity (start with 1) unique,
  cliente_id uuid references public.clientes(id) on delete set null,
  cliente_nome text not null,
  telefone text,
  origem text not null default 'WhatsApp'
    check (origem in ('Shopee','WhatsApp','Instagram','Outros')),
  numero_externo text,
  status text not null default 'novo'
    check (status in ('orcamento','novo','aguardando_pagamento','aguardando_arte',
                      'em_producao','pronto_envio','enviado','finalizado','cancelado')),
  prazo_producao date,
  prazo_entrega date,
  frete numeric(12,2) not null default 0 check (frete >= 0),
  desconto numeric(12,2) not null default 0 check (desconto >= 0),
  custo numeric(12,2) not null default 0 check (custo >= 0),
  taxa_shopee numeric(12,2) not null default 0 check (taxa_shopee >= 0),
  observacoes text,
  transportadora text,
  rastreio text,
  nf_emitida boolean not null default false,
  criado_em timestamptz not null default now(),
  criado_por text default public.nome_usuario(),
  atualizado_em timestamptz not null default now()
);
create index pedidos_status_idx on public.pedidos (status);
create index pedidos_prazo_idx on public.pedidos (prazo_producao);
create index pedidos_cliente_idx on public.pedidos (cliente_id);

create table public.pedido_itens (
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null references public.pedidos(id) on delete cascade,
  ordem integer not null default 0,
  produto text not null,
  quantidade numeric(12,2) not null check (quantidade > 0),
  valor_unitario numeric(12,2) not null default 0 check (valor_unitario >= 0),
  personalizacao text
);
create index pedido_itens_pedido_idx on public.pedido_itens (pedido_id);

create table public.pedido_historico (
