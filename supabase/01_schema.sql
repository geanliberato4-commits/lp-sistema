-- Movimento de estoque atualiza a quantidade do material (e não deixa ficar negativo)
create or replace function public.aplicar_movimento()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_atual numeric;
begin
  select m.quantidade into v_atual from public.materiais m where m.id = new.material_id for update;
  if new.tipo = 'entrada' then
    update public.materiais set quantidade = quantidade + new.quantidade, ultima_compra = current_date
     where id = new.material_id;
  elsif new.tipo = 'ajuste' then
    update public.materiais set quantidade = new.quantidade where id = new.material_id;
  else
    if v_atual < new.quantidade then
      raise exception 'Não há % em estoque (tem %).', new.quantidade, v_atual using errcode = 'P0001';
    end if;
    update public.materiais set quantidade = quantidade - new.quantidade where id = new.material_id;
  end if;
  return new;
end;
$$;
create trigger movimentos_aplicar
  before insert on public.movimentos_estoque
  for each row execute function public.aplicar_movimento();

