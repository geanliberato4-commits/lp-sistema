-- =====================================================================
-- Lista de compras com acompanhamento, contas a pagar/receber e anexos da arte.
-- =====================================================================

-- ---------- Compras ----------
create table public.compras (
  id uuid primary key default gen_random_uuid(),
  numero integer generated by default as identity (start with 1) unique,
  fornecedor text,
  status text not null default 'pendente' check (status in ('pendente','comprado','recebido','cancelado')),
  data date not null default current_date,
  previsao date,
  observacoes text,
  recebido_em timestamptz,
  criado_por text default interno.nome_usuario(),
  criado_em timestamptz not null default now()
);

create table public.compra_itens (
  id uuid primary key default gen_random_uuid(),
  compra_id uuid not null references public.compras(id) on delete cascade,
  material_id uuid not null references public.materiais(id) on delete restrict,
  em_embalagem boolean not null default false,
  quantidade numeric(12,2) not null check (quantidade > 0),
  unidades_total numeric(12,3) not null check (unidades_total > 0),
  valor numeric(12,2) not null default 0 check (valor >= 0)
);
create index compra_itens_compra_idx on public.compra_itens (compra_id);
create index compra_itens_material_idx on public.compra_itens (material_id);

-- ---------- Contas a pagar e a receber ----------
create table public.contas (
  id uuid primary key default gen_random_uuid(),
  tipo text not null check (tipo in ('pagar','receber')),
  descricao text not null,
  categoria text,
  valor numeric(12,2) not null check (valor > 0),
  vencimento date not null,
  status text not null default 'aberta' check (status in ('aberta','paga','cancelada')),
  forma text,
  pago_em date,
  caixa_id uuid references public.caixa(id) on delete set null,
  pedido_id uuid references public.pedidos(id) on delete set null,
  compra_id uuid references public.compras(id) on delete set null,
  criado_por text default interno.nome_usuario(),
  criado_em timestamptz not null default now()
);
create index contas_venc_idx on public.contas (vencimento);
create index contas_caixa_idx on public.contas (caixa_id);
create index contas_pedido_idx on public.contas (pedido_id);
create index contas_compra_idx on public.contas (compra_id);

-- Receber uma compra: entra no estoque, atualiza o custo e (opcional) lança no caixa ou cria conta a pagar
create or replace function public.receber_compra(p_compra uuid, p_pagamento text, p_forma text default 'Pix', p_vencimento date default null)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_c record;
  r record;
  v_total numeric := 0;
  v_desc text;
begin
  if not interno.eh_membro() then
    raise exception 'Seu usuário não tem acesso ao sistema.' using errcode = 'P0001';
  end if;
  select * into v_c from public.compras where id = p_compra for update;
  if not found then raise exception 'Compra não encontrada.' using errcode = 'P0001'; end if;
  if v_c.status = 'recebido' then raise exception 'Esta compra já foi recebida.' using errcode = 'P0001'; end if;
  if v_c.status = 'cancelado' then raise exception 'Esta compra foi cancelada.' using errcode = 'P0001'; end if;
  if not exists (select 1 from public.compra_itens where compra_id = p_compra) then
    raise exception 'A compra não tem itens.' using errcode = 'P0001';
  end if;

  for r in select i.*, m.unidades_embalagem from public.compra_itens i join public.materiais m on m.id = i.material_id where i.compra_id = p_compra loop
    insert into public.movimentos_estoque (material_id, tipo, quantidade, observacao)
    values (r.material_id, 'entrada', r.unidades_total, 'Compra #' || lpad(v_c.numero::text, 4, '0'));
    if r.valor > 0 then
      if r.em_embalagem and coalesce(r.unidades_embalagem, 0) > 0 then
        update public.materiais set valor_embalagem = round(r.valor / r.quantidade, 2) where id = r.material_id;
      else
        update public.materiais set custo_unitario = round(r.valor / r.unidades_total, 4), valor_embalagem = null, unidades_embalagem = null
         where id = r.material_id;
      end if;
    end if;
    v_total := v_total + r.valor;
  end loop;

  v_desc := 'Compra #' || lpad(v_c.numero::text, 4, '0') || coalesce(' · ' || v_c.fornecedor, '');
  if v_total > 0 and p_pagamento = 'caixa' then
    insert into public.caixa (tipo, categoria, descricao, valor, forma) values ('saida', 'Materiais', v_desc, v_total, coalesce(nullif(p_forma, ''), 'Pix'));
  elsif v_total > 0 and p_pagamento = 'conta' then
    insert into public.contas (tipo, descricao, categoria, valor, vencimento, compra_id)
    values ('pagar', v_desc, 'Materiais', v_total, coalesce(p_vencimento, current_date + 30), p_compra);
  end if;

  update public.compras set status = 'recebido', recebido_em = now() where id = p_compra;
end;
$$;

-- Pagar ou receber uma conta: lança no caixa uma única vez
create or replace function public.pagar_conta(p_conta uuid, p_data date default null, p_forma text default 'Pix')
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_c record;
  v_caixa uuid;
begin
  if not interno.eh_membro() then
    raise exception 'Seu usuário não tem acesso ao sistema.' using errcode = 'P0001';
  end if;
  select * into v_c from public.contas where id = p_conta for update;
  if not found then raise exception 'Conta não encontrada.' using errcode = 'P0001'; end if;
  if v_c.status <> 'aberta' then raise exception 'Esta conta não está em aberto.' using errcode = 'P0001'; end if;
  insert into public.caixa (data, tipo, categoria, descricao, valor, forma, pedido_id)
  values (coalesce(p_data, current_date), case when v_c.tipo = 'pagar' then 'saida' else 'entrada' end,
          coalesce(v_c.categoria, case when v_c.tipo = 'pagar' then 'Outras despesas' else 'Outras entradas' end),
          v_c.descricao, v_c.valor, coalesce(nullif(p_forma, ''), 'Pix'), v_c.pedido_id)
  returning id into v_caixa;
  update public.contas set status = 'paga', pago_em = coalesce(p_data, current_date), forma = coalesce(nullif(p_forma, ''), 'Pix'), caixa_id = v_caixa
   where id = p_conta;
end;
$$;

-- ---------- Anexos e arte do pedido ----------
create table public.pedido_anexos (
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null references public.pedidos(id) on delete cascade,
  tipo text not null default 'arte' check (tipo in ('arte','foto','arquivo')),
  nome text not null,
  caminho text not null,
  mime text,
  tamanho integer,
  versao integer not null default 1,
  observacao text,
  aprovado_em timestamptz,
  aprovado_obs text,
  aprovado_por text,
  enviado_por text default interno.nome_usuario(),
  criado_em timestamptz not null default now()
);
create index pedido_anexos_pedido_idx on public.pedido_anexos (pedido_id);

create or replace function public.anexo_versao()
returns trigger language plpgsql set search_path = '' as $$
begin
  if new.tipo = 'arte' then
    select coalesce(max(a.versao), 0) + 1 into new.versao from public.pedido_anexos a where a.pedido_id = new.pedido_id and a.tipo = 'arte';
  else
    new.versao := 1;
  end if;
  return new;
end; $$;
create trigger pedido_anexos_versao before insert on public.pedido_anexos
  for each row execute function public.anexo_versao();

create or replace function public.anexo_historico()
returns trigger language plpgsql set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    insert into public.pedido_historico (pedido_id, texto)
    values (new.pedido_id, case when new.tipo = 'arte' then 'Arte versão ' || new.versao || ' anexada' else 'Arquivo anexado: ' || new.nome end);
  elsif tg_op = 'UPDATE' and new.aprovado_em is not null and old.aprovado_em is null then
    insert into public.pedido_historico (pedido_id, texto)
    values (new.pedido_id, 'Arte versão ' || new.versao || ' aprovada pelo cliente' || coalesce(' (' || new.aprovado_obs || ')', ''));
  elsif tg_op = 'DELETE' then
    insert into public.pedido_historico (pedido_id, texto)
    values (old.pedido_id, 'Anexo removido: ' || old.nome);
    return old;
  end if;
  return new;
end; $$;
create trigger pedido_anexos_hist after insert or update or delete on public.pedido_anexos
  for each row execute function public.anexo_historico();

-- ---------- Segurança ----------
alter table public.compras enable row level security;
alter table public.compra_itens enable row level security;
alter table public.contas enable row level security;
alter table public.pedido_anexos enable row level security;

create policy "membro acessa compras" on public.compras
  for all to authenticated using ((select interno.eh_membro())) with check ((select interno.eh_membro()));
create policy "membro acessa itens compra" on public.compra_itens
  for all to authenticated using ((select interno.eh_membro())) with check ((select interno.eh_membro()));
create policy "membro acessa contas" on public.contas
  for all to authenticated using ((select interno.eh_membro())) with check ((select interno.eh_membro()));
create policy "membro acessa anexos" on public.pedido_anexos
  for all to authenticated using ((select interno.eh_membro())) with check ((select interno.eh_membro()));

revoke execute on function public.anexo_versao() from anon, authenticated, public;
revoke execute on function public.anexo_historico() from anon, authenticated, public;
revoke execute on function public.receber_compra(uuid, text, text, date) from anon, public;
revoke execute on function public.pagar_conta(uuid, date, text) from anon, public;
grant execute on function public.receber_compra(uuid, text, text, date) to authenticated;
grant execute on function public.pagar_conta(uuid, date, text) to authenticated;
